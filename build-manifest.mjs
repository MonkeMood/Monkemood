// Builds stickers/manifest.js from the folders inside /stickers.
//   stickers/<category>/<name>.(webp|png|jpg|jpeg|gif)
// Folder name = category, file name = sticker name (dashes become spaces).
//
// Run:  node scripts/build-manifest.mjs
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, extname, basename, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "stickers");
const exts = new Set([".webp", ".png", ".jpg", ".jpeg", ".gif"]);
const order = ["moods", "costumes", "christmas", "couples"]; // known categories first

const cats = readdirSync(dir)
  .filter((c) => statSync(join(dir, c)).isDirectory())
  .sort((a, b) => {
    const ia = order.indexOf(a), ib = order.indexOf(b);
    return (ia === -1 ? 99 : ia) - (ib === -1 ? 99 : ib) || a.localeCompare(b);
  });

const items = [];
for (const cat of cats) {
  const files = readdirSync(join(dir, cat))
    .filter((f) => exts.has(extname(f).toLowerCase()))
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));
  for (const f of files) {
    items.push({ cat, name: basename(f, extname(f)), src: `stickers/${cat}/${f}` });
  }
}

const out =
  "/* AUTO-GENERATED by scripts/build-manifest.mjs. Do not edit by hand. */\n" +
  "window.SARU_STICKERS = " + JSON.stringify(items, null, 1) + ";\n";
writeFileSync(join(dir, "manifest.js"), out);
console.log(`manifest.js: ${items.length} stickers in ${cats.length} categories (${cats.join(", ")})`);
